export function computeRiskBreakdown(zone: Zone): RiskFactorBreakdown {
  // Deterministic transparent calculation for judges:
  // Density: 35%, Growth: 25%, Flow Imbalance: 20%, Movement: 10%, Capacity: 10%
  const densityScore = Math.min(100, Math.round((zone.density / 100) * 100));
  
  const growthScore = Math.min(100, Math.max(0, Math.round((Math.max(0, zone.densityTrend) / 35) * 100)));
  
  const imbalanceRatio = zone.inflow > 0 ? (zone.inflow - zone.outflow) / Math.max(1, zone.inflow) : 0;
  const imbalanceScore = Math.min(100, Math.max(0, Math.round(imbalanceRatio * 120)));
  
  const movementScore = zone.flowDirection.includes('High') || zone.flowDirection.includes('?') ? 85 : 30;
  const capacityScore = Math.min(100, Math.round((zone.currentPeople / zone.maxCapacity) * 100));

  const totalScore = Math.round(
    (densityScore * 0.35) +
    (growthScore * 0.25) +
    (imbalanceScore * 0.20) +
    (movementScore * 0.10) +
    (capacityScore * 0.10)
  );

  let riskLevel: 'SAFE' | 'WATCH' | 'HIGH' | 'CRITICAL' = 'SAFE';
  if (totalScore >= 80 || zone.density >= 85) riskLevel = 'CRITICAL';
  else if (totalScore >= 65 || zone.density >= 70) riskLevel = 'HIGH';
  else if (totalScore >= 45 || zone.density >= 50) riskLevel = 'WATCH';

  return {
    crowdDensityWeight: 35,
    crowdDensityScore: densityScore,
    densityGrowthWeight: 25,
    densityGrowthScore: growthScore,
    flowImbalanceWeight: 20,
    flowImbalanceScore: imbalanceScore,
    movementPatternWeight: 10,
    movementPatternScore: movementScore,
    zoneCapacityWeight: 10,
    zoneCapacityScore: capacityScore,
    totalScore,
    riskLevel,
  };
}

